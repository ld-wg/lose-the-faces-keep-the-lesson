#!/usr/bin/env bash
# Copy each experiment's LaTeX artifacts (results/latex/) into paper/generated/,
# which is versioned: aggregate tables, figures and \result{} keys only — never
# faces. Only experiments whose last run finished ("done") are exported.
#
#   experiments/export_paper.sh
set -euo pipefail

root=$(cd "$(dirname "$0")/.." && pwd)
out=$root/paper/generated
mkdir -p "$out"

status() { python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["status"])' "$1"; }

for dir in "$root"/experiments/e*_*/; do
  name=$(basename "$dir")
  prov=$dir/results/provenance.json
  if [[ ! -f $prov ]]; then echo "skip $name: never run"; continue; fi
  if [[ $(status "$prov") != done ]]; then echo "skip $name: last run $(status "$prov")"; continue; fi
  rm -rf "${out:?}/$name"
  mkdir -p "$out/$name"
  cp -R "$dir/results/latex/." "$out/$name/"
  echo "exported $name"
done

# One file for the paper's preamble: \input{generated/results}
{
  echo "% generated by experiments/export_paper.sh — do not edit"
  for f in "$out"/e*_*/results.tex; do
    [[ -f $f ]] && echo "\\input{generated/$(basename "$(dirname "$f")")/results}"
  done
} > "$out/results.tex"

# Where every exported artifact came from.
python3 - "$root" <<'EOF'
import json, sys
from pathlib import Path
root = Path(sys.argv[1]); out = root / "paper" / "generated"
lines = ["# Sources of paper/generated/", "",
         "Generated by `experiments/export_paper.sh`. Do not edit by hand.", "",
         "| Experiment | Run started | Git commit | Dirty | Inputs (sha256) |", "|---|---|---|---|---|"]
for d in sorted(p for p in out.iterdir() if p.is_dir()):
    prov = root / "experiments" / d.name / "results" / "provenance.json"
    if not prov.is_file():
        continue
    p = json.loads(prov.read_text())
    inputs = ", ".join(f"{k} `{v['sha256'][:12]}`" for k, v in p.get("inputs", {}).items())
    lines.append(f"| {d.name} | {p['started']} | `{(p['git']['sha'] or '')[:10]}` | {p['git']['dirty']} | {inputs} |")
(out / "SOURCES.md").write_text("\n".join(lines) + "\n")
EOF
echo "wrote paper/generated/results.tex and SOURCES.md"
